import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {resolve} from 'node:path';
import {warehouseView} from '../src/views/warehouse.js';
import {articlesView} from '../src/views/articles.js';
import {shoppingView} from '../src/views/shopping.js';
import {routes} from '../src/core/router.js';
import {escapeHtml} from '../src/core/escape.js';
import {friendlyStorageError,validateQuantity,DATABASE_VERSION,STORE_NAMES} from '../src/data/store.js';
const root=resolve(import.meta.dirname,'..');
for(const key of ['dashboard','warehouse','articles','shopping','more'])assert.ok(routes[key]);
for(const path of ['index.html','assets/styles.css','sw.js','src/main.js','src/data/store.js','src/core/escape.js','manifest.webmanifest'])assert.ok(existsSync(resolve(root,path)),path);
const manifest=JSON.parse(readFileSync(resolve(root,'manifest.webmanifest'),'utf8'));
assert.equal(manifest.start_url,'./');assert.equal(manifest.scope,'./');assert.equal(manifest.display,'standalone');
for(const ico of manifest.icons)assert.ok(existsSync(resolve(root,ico.src)));
const shell=[...readFileSync(resolve(root,'sw.js'),'utf8').matchAll(/'\.\/[^']+'/g)].map(x=>x[0].slice(1,-1));
for(const ref of shell)assert.ok(existsSync(resolve(root,ref)),`missing offline pre-cache: ${ref}`);
assert.equal(DATABASE_VERSION,5);assert.equal(STORE_NAMES.length,9);
assert.equal(validateQuantity(1.005),1.005);
assert.throws(()=>validateQuantity(NaN),{code:'VALIDATION'});
assert.throws(()=>validateQuantity(-1e12),{code:'VALIDATION'});
assert.equal(escapeHtml('<script>'), '&lt;script&gt;');
assert.equal(friendlyStorageError({name:'QuotaExceededError'}).code,'QUOTA');
const css=readFileSync(resolve(root,'assets/styles.css'),'utf8');assert.ok(css.includes('@media(max-width:700px)'));assert.ok(css.includes('.bottom-nav'));
const versions=JSON.parse(readFileSync(resolve(root,'version.json'),'utf8'));assert.equal(versions.version,'0.7.0');
console.log('PASS: routes, safe HTML, validation, migration schema, PWA shell inventory, version');
