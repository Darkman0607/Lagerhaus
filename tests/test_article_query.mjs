import assert from 'node:assert/strict';
import {installFakeIndexedDB,resetFakeDatabases} from './fake-indexeddb.mjs';
installFakeIndexedDB();resetFakeDatabases();
const {articleContext,filterAndSort,normalizePreferences}=await import('../src/data/article-query.js');
const {createCatalogArticle,setArticleFavorite}=await import('../src/data/catalog.js');
const {repository}=await import('../src/data/store.js');
const {articlesView,clearArticleMediaUrls}=await import('../src/views/articles.js');
const {setArticleThreshold}=await import('../src/data/bookings.js');
const {listCategories}=await import('../src/data/categories.js');
const common={category:'Werkzeug',locationName:'Garage',unit:'Stück',articleKind:'device'};
const a=await createCatalogArticle({...common,name:'USB-C Kabel',brand:'Anker',model:'X3',tags:'USB-C, Ladegerät',quantity:3,section:'privat'});
const b=await createCatalogArticle({...common,name:'Akku Schrauber',locationId:a.primaryLocationId,quantity:0,section:'arbeit',favorite:true});
const c=await createCatalogArticle({...common,name:'Ersatzteile',locationId:a.primaryLocationId,quantity:2,section:'gemeinsam'});
const state=async()=>{const [items,stocks,locations,categories]=await Promise.all([repository.articles(),repository.stocks(),repository.locations(),listCategories()]);return items.map(i=>articleContext(i,stocks,locations,categories));};
let all=await state();const find=(id)=>all.find(x=>x.id===id);
assert.match(find(a.id).search,/usb-c/);assert.match(find(a.id).search,/anker/);
assert.ok(find(a.id).search.includes(a.id.slice(0,8)));
assert.equal(find(a.id).quantity,3);assert.equal(find(b.id).status,'rot');
assert.equal(filterAndSort(all,{query:'usb-c anker'}).map(x=>x.id).join(','),a.id);
assert.equal(filterAndSort(all,{section:'privat'}).length,2,'privat plus gemeinsam');
assert.equal(filterAndSort(all,{section:'arbeit'}).length,2,'arbeit plus gemeinsam');
assert.equal(filterAndSort(all,{section:'gemeinsam'}).length,1);
assert.equal(filterAndSort(all,{section:'arbeit',status:'rot',favorite:true}).map(x=>x.id).join(','),b.id);
assert.equal(filterAndSort(all,{query:'usb-c',section:'arbeit'}).length,0);
assert.equal(filterAndSort(all,{kind:'device',location:a.primaryLocationId}).length,3);
const catId=(await listCategories()).find(x=>x.name==='Werkzeug').id;
assert.equal(filterAndSort(all,{category:catId}).length,3);
assert.equal(filterAndSort(all,{sort:'quantity'})[0].id,a.id);
assert.deepEqual(filterAndSort(all,{sort:'name'}).map(x=>x.name),['Akku Schrauber','Ersatzteile','USB-C Kabel']);
assert.equal(filterAndSort(all,{query:'usb-c'}).length,1);
assert.equal(filterAndSort(all,{changed:'7'},Date.now()+20*86400000).length,0);
assert.equal(normalizePreferences({layout:'bad',sort:'nope'}).sort,'name');
await setArticleFavorite(a.id,true);assert.equal((await repository.articles()).find(x=>x.id===a.id).favorite,true);
assert.equal((await repository.stocks()).find(s=>s.articleId===a.id).quantity,3,'favorite must not alter stock');
assert.equal((await repository.movements(a.id)).length,1,'favorite must not create stock movement');
await setArticleThreshold({articleId:a.id,minQuantity:4});all=await state();assert.equal(find(a.id).status,'orange');
const html=await articlesView();for(const expected of ['u07-table-scroll','catalog-card-list','data-catalog-filter="query"','data-catalog-filter="status"','data-catalog-filter="favorite"','data-catalog-filter="sort"','catalog-details','ART-'])assert.ok(html.includes(expected),expected);
clearArticleMediaUrls();
console.log('PASS U07: exact matching, combined filters, favoriting with stock preservation, sort, status, responsive list/detail controls');
